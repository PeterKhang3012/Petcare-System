CREATE TABLE payment_attempts (
    payment_id VARCHAR(36) NOT NULL,
    booking_id VARCHAR(24) NOT NULL,
    owner_id VARCHAR(24) NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    vnp_txn_ref VARCHAR(100) NOT NULL,
    amount BIGINT NOT NULL,
    currency VARCHAR(3) NOT NULL,
    status VARCHAR(16) NOT NULL,
    booking_expires_at DATETIME(6) NOT NULL,
    vnp_transaction_no VARCHAR(32),
    vnp_response_code VARCHAR(8),
    vnp_transaction_status VARCHAR(8),
    verified_at DATETIME(6),
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    PRIMARY KEY (payment_id),
    CONSTRAINT uq_payment_owner_key UNIQUE (owner_id, idempotency_key),
    CONSTRAINT uq_payment_vnp_ref UNIQUE (vnp_txn_ref),
    CONSTRAINT ck_payment_amount CHECK (amount > 0),
    CONSTRAINT ck_payment_status CHECK (status IN ('PENDING', 'SUCCEEDED', 'FAILED')),
    KEY ix_payment_booking (booking_id),
    KEY ix_payment_status_created (status, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE payment_outbox (
    event_id VARCHAR(36) NOT NULL,
    payment_id VARCHAR(36) NOT NULL,
    payload TEXT NOT NULL,
    status VARCHAR(16) NOT NULL,
    attempts INT NOT NULL DEFAULT 0,
    next_attempt_at DATETIME(6) NOT NULL,
    lease_until DATETIME(6),
    lease_owner VARCHAR(128),
    booking_outcome VARCHAR(64),
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    PRIMARY KEY (event_id),
    CONSTRAINT fk_outbox_payment FOREIGN KEY (payment_id) REFERENCES payment_attempts (payment_id),
    CONSTRAINT ck_outbox_attempts CHECK (attempts >= 0),
    CONSTRAINT ck_outbox_status CHECK (status IN ('PENDING', 'DELIVERED', 'REJECTED', 'DEAD_LETTER')),
    KEY ix_outbox_pending (status, next_attempt_at, lease_until),
    KEY ix_outbox_payment (payment_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
